test('messages require an explicit send and recover from Enter, synthetic composition and UTF-8 validation', async ({ page, app }) => {
  await app.openPeer()
  const composer = page.locator('.composer textarea')
  const baseline = await app.count('message.send')
  await composer.fill('Fictional message draft')
  await composer.press('End')
  await composer.press('Enter')
  await expect(composer).toHaveValue('Fictional message draft\n')
  expect(await app.count('message.send'), 'plain Enter only inserts a newline').toBe(baseline)

  // Synthetic DOM composition is a regression check, not native IME acceptance.
  await composer.evaluate(element => {
    element.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true, data: 'あ' }))
    element.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', code: 'Enter', ctrlKey: true, isComposing: true, bubbles: true }))
    element.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true, data: 'あ' }))
  })
  expect(await app.count('message.send'), 'composition confirmation must not send').toBe(baseline)

  await composer.fill('あ'.repeat(5462))
  await page.getByRole('button', { name: 'Send message', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('displayed UTF-8 byte limit')
  await expect(composer).toHaveValue('あ'.repeat(5462))
  expect(await app.count('message.send'), 'oversized UTF-8 text stays local').toBe(baseline)

  await composer.fill('Fictional notes are ready for review.')
  await page.getByRole('button', { name: 'Send message', exact: true }).click()
  await expect(composer).toHaveValue('')
  await app.expectState(state => state.messages.some(message =>
    message.direction === 'outgoing' && message.text === 'Fictional notes are ready for review.' && message.status === 'sent'), 'explicit English send reaches the real peer')
  expect(await app.count('message.send')).toBe(baseline + 1)

  await composer.fill('Draft survives navigation')
  await page.getByRole('button', { name: 'Network graph', exact: true }).click()
  await expect(page.locator('.network-graph')).toBeVisible()
  await page.goBack()
  await expect(composer).toBeVisible()
  await expect(composer).toHaveValue('Draft survives navigation')
  await page.goForward()
  await expect(page.locator('.network-graph')).toBeVisible()
  await app.openPeer()
  await expect(composer).toHaveValue('Draft survives navigation')

  await app.appearance('ja', 'dark')
  await composer.fill('表示確認用の資料を共有します。内容を確認してください。')
  await page.getByRole('button', { name: 'メッセージを送信', exact: true }).click()
  await expect(composer).toHaveValue('')
  await app.expectState(state => state.messages.some(message =>
    message.direction === 'outgoing' && message.text === '表示確認用の資料を共有します。内容を確認してください。' && message.status === 'sent'), 'explicit Japanese send reaches the real peer')
  expect(await app.count('message.send')).toBe(baseline + 2)
})

