// Every test gets a fresh Studio process, authenticated context and private
// receiving root. Actions use the UI; state predicates observe the real Go app.
const studio = state => state.peers.find(peer => peer.name === 'Studio')
const pendingOutgoing = state => state.transfers.filter(transfer =>
  transfer.direction === 'outgoing' && ['offered', 'awaiting-acceptance'].includes(transfer.status))
const activeOutgoing = state => state.transfers.filter(transfer =>
  transfer.direction === 'outgoing' && ['offered', 'awaiting-acceptance', 'queued', 'transferring', 'saving'].includes(transfer.status))
const fileInput = page => page.locator('.conversation input[type=file]:not([webkitdirectory])')
const dialog = page => page.getByRole('dialog')
const serviceName = page => dialog(page).locator('input[required][maxlength="64"]')
const servicePorts = page => dialog(page).locator('input[aria-describedby="port-help"]')
const serviceLocalPort = page => dialog(page).locator('input[inputmode="numeric"]')
const serviceRow = (page, name) => page.locator('.service-rows > article').filter({
  has: page.locator('strong').filter({ hasText: new RegExp(`^${name}$`) }),
})

async function closeDialog(page) {
  await page.keyboard.press('Escape')
  await expect(dialog(page)).toHaveCount(0)
}

async function showDetails(page, app) {
  if (!await page.locator('.details-panel').isVisible()) await app.openDetails()
  await expect(page.locator('.details-panel')).toBeVisible()
}

async function openConnection(page) {
  await page.locator('.conversation-header').getByRole('button', { name: 'Connect to a service', exact: true }).click()
  await expect(dialog(page)).toBeVisible()
}

async function expectPrivateValue(locator, value, description) {
  // Assertions return only a boolean so a failure cannot print a private path.
  await expect.poll(() => locator.evaluate((element, expected) => element.value === expected, value), { message: description }).toBe(true)
}

async function uploads(page) {
  return page.evaluate(() => window.__sobaQA.uploads)
}

async function stageWithRequiredRetry(page, app, name, contents, captureFailure = false) {
  const source = await app.sourceFile(name, contents)
  await fileInput(page).setInputFiles(source)
  const preview = page.locator('.batch-preview')
  await expect(preview).toContainText(name)
  await preview.locator('.batch-footer .button-primary').click()

  // The real fixture fails the first staging request on every fresh instance.
  // Keep this explicit for each workflow that needs an actual pending offer.
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.locator('.upload-progress')).toHaveCount(0)
  await expect(preview).toContainText(name)
  expect(await uploads(page), 'failed staging must not retry automatically').toBe(1)
  await app.expectState(state => pendingOutgoing(state).length === 0, 'failed staging creates no outgoing offer')
  if (captureFailure) await app.capture('upload-staging-failure-en-light-1440')

  await preview.locator('.batch-footer .button-primary').click()
  await expect(preview).toHaveCount(0)
  await app.expectState(state => pendingOutgoing(state).length === 1, 'manual retry creates one outgoing offer')
  expect(await uploads(page), 'one manual retry makes exactly two staging attempts').toBe(2)
  expect(await page.evaluate(() => {
    const qa = window.__sobaQA
    return qa.duplicateUploadIdentity && qa.uploadIDs.length === 2 && qa.uploadIDs[0] === qa.uploadIDs[1]
  }), 'retry must reuse the original upload identity').toBe(true)
}

