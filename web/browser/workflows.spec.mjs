test('real Core discovery rejects altered advertised scope without creating a listener', async ({ page, app }) => {
  await app.openPeer('services')
  await app.openDetails()
  await page.getByRole('button', { name: 'Check shared services', exact: true }).click()
  await app.expectState(state => state.availableServices.some(service => service.peerId === 'fixture-studio' && service.purpose === 'web' && service.revision && service.checkedAt))
  // Only fictional metadata stays in page memory. The result deliberately
  // contains booleans/codes, never the local session or request credential.
  for (const change of ['purpose', 'ports', 'grant']) {
    const outcome = await page.evaluate(async ({ change, localPort }) => {
      const state = await (await fetch('/api/state')).json()
      const advertised = state.availableServices.find(service => service.peerId === 'fixture-studio' && service.network === 'tcp' && service.ports === '8080')
      if (!advertised?.revision || !advertised.checkedAt) return { metadata: false }
      const payload = { name: 'rejected-advertised-change', backend: 'tailnet', peerId: advertised.peerId, serviceId: advertised.id, serviceRevision: advertised.revision, network: advertised.network, ports: advertised.ports, purpose: advertised.purpose, localPort, loopbackHost: '127.0.0.1', lifetime: 'until-stopped', ttlSeconds: 0, discoverable: false }
      if (change === 'purpose') payload.purpose = 'ssh'
      if (change === 'ports') payload.ports = '8081'
      if (change === 'grant') payload.serviceId = 'fictional-replaced-grant'
      const response = await fetch('/api/command', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': state.csrfToken }, body: JSON.stringify({ requestId: crypto.randomUUID(), name: 'service.connect', payload }) })
      const body = await response.json()
      return { metadata: true, refused: !response.ok, code: body.code }
    }, { change, localPort: app.localServicePort })
    expect(outcome).toEqual({ metadata: true, refused: true, code: 'discovery_review_changed' })
  }
  await app.expectState(state => !state.services.some(service => service.name === 'rejected-advertised-change'))
})
